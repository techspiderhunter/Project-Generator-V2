function callLLM(string $systemPrompt, string $userPrompt, string $model = 'gemini-1.5-pro', float $temperature = 0.2): string {
    $geminiKey = getenv('GEMINI_API_KEY');
    $openaiKey = getenv('OPENAI_API_KEY');
    $anthropicKey = getenv('ANTHROPIC_API_KEY');

    // 1. Try Gemini API if key is set or model starts with gemini
    if ($geminiKey) {
        $cleanModel = str_replace('models/', '', $model ?: 'gemini-1.5-pro');
        $url = "https://generativelanguage.googleapis.com/v1beta/models/{$cleanModel}:generateContent?key={$geminiKey}";
        
        $body = [
            'system_instruction' => [
                'parts' => [['text' => $systemPrompt]]
            ],
            'contents' => [
                ['role' => 'user', 'parts' => [['text' => $userPrompt]]]
            ],
            'generationConfig' => [
                'temperature' => $temperature,
            ]
        ];

        $ch = curl_init($url);
        curl_setopt_array($ch, [
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_POST => true,
            CURLOPT_HTTPHEADER => ['Content-Type: application/json'],
            CURLOPT_POSTFIELDS => json_encode($body),
            CURLOPT_TIMEOUT => 60
        ]);
        $response = curl_exec($ch);
        $httpCode = curl_getinfo($ch, CURLINFO_HTTP_CODE);
        curl_close($ch);

        if ($httpCode === 200) {
            $data = json_decode($response, true);
            $text = $data['candidates'][0]['content']['parts'][0]['text'] ?? null;
            if ($text) return trim($text);
        }
    }

    // 2. Try OpenAI API if key is set
    if ($openaiKey) {
        $openaiModel = str_contains($model, 'gpt') ? $model : 'gpt-4o';
        $ch = curl_init('https://api.openai.com/v1/chat/completions');
        $body = [
            'model' => $openaiModel,
            'messages' => [
                ['role' => 'system', 'content' => $systemPrompt],
                ['role' => 'user', 'content' => $userPrompt]
            ],
            'temperature' => $temperature
        ];
        curl_setopt_array($ch, [
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_POST => true,
            CURLOPT_HTTPHEADER => [
                'Content-Type: application/json',
                "Authorization: Bearer $openaiKey"
            ],
            CURLOPT_POSTFIELDS => json_encode($body),
            CURLOPT_TIMEOUT => 60
        ]);
        $response = curl_exec($ch);
        $httpCode = curl_getinfo($ch, CURLINFO_HTTP_CODE);
        curl_close($ch);

        if ($httpCode === 200) {
            $data = json_decode($response, true);
            $text = $data['choices'][0]['message']['content'] ?? null;
            if ($text) return trim($text);
        }
    }

    // 3. Fallback: Local Simulation Generator (so workflow executes end-to-end even without active API keys)
    return generateAutonomousSimulation($systemPrompt, $userPrompt);
}

